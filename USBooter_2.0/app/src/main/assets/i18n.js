  function supported() { return Object.keys(DICT); }

  function detect() {
    var saved = null;
    try { saved = localStorage.getItem('lang'); } catch (e) {}
    if (saved && DICT[saved]) return saved;
    var nav = (navigator.language || 'en').toLowerCase();
    if (nav.indexOf('it') === 0) return 'it';
    if (nav.indexOf('es') === 0) return 'es';
    if (nav.indexOf('pt') === 0) return 'pt';
    if (nav.indexOf('zh') === 0) return 'zh';
    return 'en';
  }

  function t(key, vars) {
    var s = (DICT[current] && DICT[current][key]);
    if (s == null) s = DICT.en[key];
    if (s == null) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  }

  /** Translates a status string produced by the Android side, keeping any suffix. */
  function tNative(text) {
    if (!text) return text;
    if (current === 'en') return text;
    // "<message> 42%" progress updates: translate the message, keep the number.
    var pct = /^([\s\S]*?)(\s\d{1,3}%)$/.exec(text);
    if (pct) return tNativeBase(pct[1]) + pct[2];
    return tNativeBase(text);
  }

